function buildModularConfig()
%buildModularConfig  Create the full modular config directory structure.
%
%  Run ONCE to set up the sandbox config folders. Creates:
%    config/runs/           — Run files (top-level, pass to runSingleScenario)
%    config/sensors/<TYPE>/ — One folder per sensor type (default + template + my_)
%    config/targets/<TYPE>/ — One folder per target behavior
%    config/terrain/<TYPE>/ — One folder per terrain type
%    config/trackers/<TYPE>/— One folder per tracker algorithm
%
%  USAGE
%    cd to adeptus-rainyday-tracking root, then:
%    addpath('scripts');
%    buildModularConfig
%
%  Existing files are NOT overwritten. Safe to re-run.

root = fileparts(fileparts(mfilename('fullpath')));
configDir = fullfile(root, 'config');
fprintf('\n[BUILD] Creating modular config structure in:\n  %s\n\n', configDir);

%% ========================================================================
%  RUNS — top-level files that reference all other components
%% ========================================================================
