function mkd(d)
    if ~exist(d, 'dir'); mkdir(d); end
end

function writeIfNew(filepath, content)
    if exist(filepath, 'file')
        return;  % never overwrite
    end
    fid = fopen(filepath, 'w', 'n', 'UTF-8');
    fprintf(fid, '%s', content);
    fclose(fid);
end

function txt = prettyJson(s)
    txt = jsonencode(s, 'PrettyPrint', true);
    % Strip placeholder workaround (MATLAB can't encode empty struct as {})
    txt = regexprep(txt, '\{\s*"placeholder":\s*0\s*\}', '{}');
end

