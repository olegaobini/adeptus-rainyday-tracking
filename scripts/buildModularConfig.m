mkd(runsDir);

writeIfNew(fullfile(runsDir, 'dasr_baseline.json'), prettyJson(struct( ...
    'description', 'DASR baseline: PSR+SSR, two gentle-turn targets, rural terrain, clear weather', ...
    'sensors', {{'PSR/default_PSR', 'SSR/default_SSR'}}, ...
    'targets', 'gentle_turn/default_gentle_turn', ...
    'terrain', 'rural/default_rural', ...
    'trackers', {{'GNN/default_GNN', 'JPDA/default_JPDA'}}, ...
    'degradation', struct('enabled', false, 'type', 'rain'), ...
    'platforms', struct('placeholder',0), ...
    'output', struct('show_visuals',true,'animate_visuals',true, ...
        'save_results',true,'print_diagnostics',true,'results_directory','results') ...
)));

writeIfNew(fullfile(runsDir, 'demo_mountain.json'), prettyJson(struct( ...
    'description', 'Demo: PSR, 5 crossing targets, mountain terrain, clear weather (Boeing demo)', ...
